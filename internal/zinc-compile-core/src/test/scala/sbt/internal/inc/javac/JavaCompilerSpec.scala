object JavaCompilerSpec extends Properties:
  override def tests: List[Test] = List(
    example("Compiling a java file with local javac should compile a java file", works(local)),
    example("issue errors and warnings", findsErrors(local)),
    example(
      "Compiling a file with forked javac should compile a java file",
      works(forked, forked = true)
    ),
    example("issue errors and warnings (forked)", findsErrors(forked)),
    example("yield the same errors as local javac", forkSameAsLocal),
    example("Documenting a file with forked javadoc should document a java file", docWorks(forked)),
    example("find errors in a java file", findsDocErrors(forked)),
    example(
      "Analyzing classes generated by javac should match APIs for stable static-final fields",
      analyzeStaticDifference("String", "\"A\"", "\"A\"")
    ),
    example(
      "different APIs for static-final fields with changed values",
      analyzeStaticDifference("String", "\"A\"", "\"B\"")
    ),
    example(
      "different APIs for static-final fields with changed types",
      analyzeStaticDifference("String", "\"1\"", "int", "1")
    ),
    example(
      "\"safe\" singleton type names",
      analyzeStaticDifference("float", "0.123456789f", "0.123456789f")
    ),
    property(
      "match APIs for static-final fields exactly when their values match",
      propStaticDifference
    ).withTests(5),
  )

  def docWorks(compiler: XJavaTools): Result = IO.withTemporaryDirectory { out =>
    val (result, _) = doc(compiler, Seq(knownSampleGoodFile), Seq(), out.toPath)
    Result.all(
      List(
        Result.assert(result),
        Result.assert(new File(out, "index.html").exists),
        Result.assert(new File(out, "good.html").exists),
      )
    )
  }

  def dealiasSymlinks(xs: HashSet[File]): HashSet[String] = xs.map(_.getCanonicalPath)

  def works(compiler: XJavaTools, forked: Boolean = false): Result = IO.withTemporaryDirectory {
    out =>
      val classfileManager = new CollectingClassFileManager()
      val (result, _) = compile(
        compiler,
        Seq(knownSampleGoodFile),
        Seq("-deprecation"),
        out.toPath,
        incToolOptions = IncToolOptionsUtil
          .defaultIncToolOptions()
          .withClassFileManager(Optional.of(classfileManager: ClassFileManager))
          .withUseCustomizedFileManager(true)
      )
      val classfile = new File(out, "good.class")
      val generated = dealiasSymlinks(classfileManager.generatedClasses.map {
        case vf: PathBasedFile => vf.toPath.toFile
      })
      val invoked = Using.resource(new URLClassLoader(Array(out.toURI.toURL))) { cl =>
        cl.loadClass("good").getDeclaredMethod("test").invoke(null)
      }
      Result.all(
        List(
          Result.assert(result),
          Result.assert(classfile.exists),
          generated ==== (if forked then HashSet() else dealiasSymlinks(HashSet(classfile))),
          invoked ==== "Hello",
        )
      )
  }

  private def compileOptions: Seq[String] =
    Seq("-deprecation") ++
      (if scala.util.Properties.isJavaAtLeast("21") then Seq("-proc:none")
       else Nil)

  def findsErrors(compiler: XJavaTools): Result = IO.withTemporaryDirectory { out =>
    val (result, problems) =
      compile(compiler, Seq(knownSampleErrorFile), compileOptions, out.toPath)
    val expected = List(
      warnOnLine(lineno = 12, colno = 15, lineContent = Some("java.rmi.RMISecurityException")),
      errorOnLine(14, 7),
      errorOnLine(15, 11),
      warnOnLine(18, 18),
      warnOnLine(18, 14), // could be expected depending on Java version
      errorOnLine(lineno = 25, colno = 9, message = Some("not an enclosing class: C.D")),
    )
    Result.all(
      List(result ==== false, problems.size ==== 5) ++
        problems.toList.map(matchesOneOf(_, expected))
    )
  }

  def findsDocErrors(compiler: XJavaTools): Result = IO.withTemporaryDirectory { out =>
    val (result, problems) = doc(compiler, Seq(knownSampleErrorFile), Seq(), out.toPath)
    val expected = List(errorOnLine(14, 7), errorOnLine(15, 11))
    Result.all(
      List(result ==== false, problems.size ==== 2) ++
        problems.toList.map(matchesOneOf(_, expected))
    )
  }

  /**
   * Compiles with the given constant values, and confirms that if the strings mismatch, then the
   * the APIs mismatch.
   */
  def analyzeStaticDifference(typeName: String, left: String, right: String): Result =
    analyzeStaticDifference(typeName, left, typeName, right)

  def analyzeStaticDifference(
      leftType: String,
      left: String,
      rightType: String,
      right: String
  ): Result =
    def compileWithPrimitive(templateType: String, templateValue: String) =
      IO.withTemporaryDirectory { out =>
        // copy the input file to a temporary location and change the templateValue
        val input = out.toPath.resolve(hasStaticFinalFile.getFileName.toString)
        IO.writeLines(
          input.toFile,
          IO.readLines(hasStaticFinalFile.toFile).map { line =>
            line.replace("TYPE", templateType).replace("VALUE", templateValue)
          }
        )
        // then compile it
        val (result, _) = compile(local, Seq(input), Seq(), out.toPath)
        if !result then sys.error(s"failed to compile $templateType = $templateValue")
        Using.resource(new URLClassLoader(Array(out.toURI.toURL))) { loader =>
          ClassToAPI(Seq(loader.loadClass("hasstaticfinal")))
        }
      }
    // compile with two different primitive values, and confirm that they match if their
    // values match
    val leftAPI = compileWithPrimitive(leftType, left)
    val rightAPI = compileWithPrimitive(rightType, right)
    Result.all(
      List(
        leftAPI.size ==== rightAPI.size,
        leftAPI.lazyZip(rightAPI).forall(SameAPI.apply) ==== (left == right),
      )
    )
  end analyzeStaticDifference

  private val genLiteral: Gen[(String, String)] =
    Gen.choice1(
      Gen.int(Range.linear(-1000, 1000)).map(i => "int" -> i.toString),
      Gen.string(Gen.alphaNum, Range.linear(0, 8)).map(s => "String" -> s"\"$s\""),
    )

  def propStaticDifference: Property =
    for
      (leftType, left) <- genLiteral.forAll
      (rightType, right) <- Gen.choice1(Gen.constant(leftType -> left), genLiteral).forAll
    yield analyzeStaticDifference(leftType, left, rightType, right)

  private case class ExpectedProblem(
      lineno: Int,
      colno: Int,
      severity: Severity,
      message: Option[String],
      lineContent: Option[String]
  ):
    def matches(p: Problem): Boolean =
      def lineNumberCheck = p.position.line.isPresent && (p.position.line.get == lineno)
      def columnCheck = p.position.pointer.isPresent && (p.position.pointer.get == colno)
      def messageCheck = message.forall(p.message.contains)
      def lineContentCheck = lineContent.forall(p.position.lineContent.contains)
      lineNumberCheck && columnCheck && messageCheck && lineContentCheck && p.severity == severity

    override def toString: String =
      val msg = message.fold("")(s => s""" with message = "$s"""")
      val content = lineContent.fold("")(s => s""" with content = "$s"""")
      s"$severity on line $lineno, column $colno$msg$content"

  private def matchesOneOf(p: Problem, expected: List[ExpectedProblem]): Result =
    Result
      .assert(expected.exists(_.matches(p)))
      .log(s"Expected one of ${expected.mkString("; ")}, but found $p")

  private def errorOnLine(
      lineno: Int,
      colno: Int,
      message: Option[String] = None,
      lineContent: Option[String] = None
  ) = ExpectedProblem(lineno, colno, Severity.Error, message, lineContent)

  private def warnOnLine(
      lineno: Int,
      colno: Int,
      message: Option[String] = None,
      lineContent: Option[String] = None
  ) = ExpectedProblem(lineno, colno, Severity.Warn, message, lineContent)

  def forkSameAsLocal: Result = IO.withTemporaryDirectory { out =>
    val (fresult, fproblems) =
      compile(forked, Seq(knownSampleErrorFile), compileOptions, out.toPath)
    val (lresult, lproblems) =
      compile(local, Seq(knownSampleErrorFile), compileOptions, out.toPath)
    def line(p: Problem) = if p.position.line.isPresent then Some(p.position.line.get) else None
    Result.all(
      (fresult ==== lresult) :: fproblems.toList.zip(lproblems).flatMap { (f, l) =>
        // TODO - We should check to see if the levenshtein distance of the messages is close...
        // if (f.position.sourcePath.isPresent)
        //   assert(f.position.sourcePath.get == l.position.sourcePath.get)
        // else assert(!l.position.sourcePath.isPresent)
        List(line(f) ==== line(l), f.severity ==== l.severity)
      }
    )
  }

  def compile(
      c: XJavaTools,
      sources: Seq[Path],
      args: Seq[String],
      output: Path,
      incToolOptions: IncToolOptions = IncToolOptionsUtil.defaultIncToolOptions()
  ): (Boolean, Array[Problem]) =
    val log = LoggerContext.globalContext.logger("JavaCompilerSpec", None, None)
    val reporter = new ManagedLoggedReporter(10, log)
    val result = c.javac.run(
      sources.map(x => PlainVirtualFile(x)).toArray,
      args.toArray,
      CompileOutput(output),
      incToolOptions,
      reporter,
      log
    )
    (result, reporter.problems)

  def doc(
      c: XJavaTools,
      sources: Seq[Path],
      args: Seq[String],
      output: Path,
      incToolOptions: IncToolOptions = IncToolOptionsUtil.defaultIncToolOptions()
  ): (Boolean, Array[Problem]) =
    val log = LoggerContext.globalContext.logger("JavaCompilerSpec", None, None)
    val reporter = new ManagedLoggedReporter(10, log)
    val result = c.javadoc.run(
      sources.map(x => PlainVirtualFile(x)).toArray,
      args.toArray,
      CompileOutput(output),
      incToolOptions,
      reporter,
      log
    )
    (result, reporter.problems)

  // TODO - Create one with known JAVA HOME.
  def forked = JavaTools(JavaCompiler.fork(), Javadoc.fork())

  def local =
    JavaTools(
      JavaCompiler.local.getOrElse(sys.error("This test cannot be run on a JRE, but only a JDK.")),
      Javadoc.local.getOrElse(Javadoc.fork())
    )

  def knownSampleErrorFile = loadTestResource("test1.java")
  def knownSampleGoodFile = loadTestResource("good.java")
  def hasStaticFinalFile = loadTestResource("hasstaticfinal.java")

  def loadTestResource(name: String): Path = Paths.get(getClass.getResource(name).toURI)
end JavaCompilerSpec
